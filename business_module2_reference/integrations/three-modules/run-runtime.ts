/** Module2 actively calls Module1 and Module3 over loopback HTTP; no model API or production knowledge writes. */
import {readFileSync,writeFileSync,existsSync,mkdirSync} from 'node:fs';
import {join,resolve} from 'node:path';
import {createHash} from 'node:crypto';
import {makeModule1ReviewInbox,validateM3Packet} from '../../lib/module3-integration';
import type {M2EvidenceSearchRequest,M3SearchResponse,M3Packet} from '../../lib/module3-integration';
const all=resolve(__dirname,'../../../..'), ex=join(all,'shared_exchange');
const load=(name:string)=>JSON.parse(readFileSync(join(ex,name),'utf8'));
const post=async(base:string,path:string,input:unknown)=>{
  const response=await fetch(base+path,{method:'POST',headers:{'Content-Type':'application/json'},body:JSON.stringify(input)});
  const data=await response.json() as any;
  return {status:response.status,data};
};
const must=(p:boolean,m:string)=>{if(!p)throw Error(m);};
const m1='http://127.0.0.1:8799',m3='http://127.0.0.1:8798';
(async()=>{
  // These files are regenerated by the *real* Module2 decision engine in run.ts.
  const proposed=load('module2-to-module1-next-preparation.json');
  const request=load('module2-to-module3-search.json') as M2EvidenceSearchRequest;
  const feed=validateM3Packet(load('module3-external-candidates.json') as M3Packet);
  const sourceResponse=await post(m1,'/test/prepare',{selectedOptionIds:['needs','followup']});
  must(sourceResponse.status===200,'M1 real prepare failed');
  const source=sourceResponse.data.sheet;
  must(source.priorities.map((x:any)=>x.id).join(',')==='needs,followup','Original frozen training choices mismatch');
  const candidate={...proposed,sourceSheetHash:sourceResponse.data.sheetHash};
  const digest=createHash('sha256').update(JSON.stringify(candidate)).digest('hex');
  const reviewedAt='2026-11-03T08:00:00Z';
  const decision={action:'ADOPT_TEST_ONLY',status:'REVIEWED_TEST_ONLY',candidateHash:digest,
    reviewer:'fixture-reviewer-training',reviewId:'review-http-integration-001',reviewedAt};
  const rejected=await post(m1,'/test/apply',{sourceSheetId:source.id,candidate,decision:{...decision,status:'UNREVIEWED'}});
  must(rejected.status===403,'M1 accepted unreviewed proposal');
  const applied=await post(m1,'/test/apply',{sourceSheetId:source.id,candidate,decision});
  must(applied.status===200,'M1 reviewed proposal was not accepted');
  const newSheet=applied.data.sheet;
  must(newSheet.priorities.map((x:any)=>x.id).join(',')==='needs,evidence_scope','M1 did not actually change plan');
  must(newSheet.id!==source.id,'M1 mutated original plan');
  const actualPractice=await post(m1,'/test/practice',{sheetId:newSheet.id,optionId:'evidence_scope',
    answer:'这次我先确认您想核对哪类人群。C-17只有A类的X，没有同期比较组，B类和Y都没有依据，所以不能说更好。没核实的我查原始资料，明天下午跟您确认，今天不把还没查的说成已经做完。'});
  must(actualPractice.status===200,'M1 engine practice run failed');
  must(actualPractice.data.run.state==='review' && actualPractice.data.run.review?.observations?.length===3,
    'M1 actual engine did not produce source-bound criteria');
  const repeated=await post(m1,'/test/apply',{sourceSheetId:source.id,candidate,decision});
  must(repeated.status===200&&repeated.data.sheet.id===newSheet.id,'M1 replay not idempotent');
  const search=await post(m3,'/test/search',request);
  must(search.status===200,'M3 HTTP search failed');
  const reply=search.data as M3SearchResponse;
  const inbox=makeModule1ReviewInbox(request,reply,feed);
  must(inbox.candidates.length>0,'M3 source did not match requested topic');
  const hit=inbox.candidates[0];
  const premature=await post(m1,'/test/review-external',{inbox,sourceId:hit.sourceId,reviewer:'fixture-medical-reviewer-1',
     decision:'APPROVE_FOR_PRODUCTION',evidenceHash:hit.sourceVersion});
  must(premature.status===403,'Unreviewed web source was promoted to production medical knowledge');
  const reviewed=await post(m1,'/test/review-external',{inbox,sourceId:hit.sourceId,reviewer:'fixture-medical-reviewer-1',
     decision:'ACCEPT_FOR_TEST_READING',evidenceHash:hit.sourceVersion});
  must(reviewed.status===200,'M1 test reading review failed');
  must(reviewed.data.canUseAsMedicalKnowledge===false && reviewed.data.canUpdateKnowledgeVersion===false &&
       reviewed.data.canUseForTestReading===true,'M1 wrongly approved medical source');
  const invalid=await post(m3,'/test/search',{...request,queryTerm:' '});
  must(invalid.status===400,'M3 accepted empty search');
  const result={kind:'THREE_MODULE_HTTP_TEST_V2',usage:'TEST_ONLY',
    runtime:{m1:'Python module1 Engine.prepare / new-sheet adoption via HTTP',
      m2:'TypeScript decision engine-generated candidate + HTTP orchestrator',
      m3:'MedRep Daily assemble(SEEDS) + HTTP search'},
    module1:{originalSheetId:source.id,originalSelected:source.priorities.map((x:any)=>x.id),
      newSheetId:newSheet.id,newSelected:newSheet.priorities.map((x:any)=>x.id),
      added:applied.data.receipt.added,displaced:applied.data.receipt.displaced,
      originalStillImmutable:true,replayedIdempotently:true,
      practice:{state:actualPractice.data.run.state,attempt:actualPractice.data.run.attempt,
        criteria:actualPractice.data.run.review.observations.map((x:any)=>({id:x.criterion_id,status:x.status,
          anchored:Boolean(x.quote&&actualPractice.data.run.transcript[x.turn_index]?.text.includes(x.quote))})),
        medicalAccuracy:actualPractice.data.run.review.medical_accuracy}},
    module3:{query:request.queryTerm,matchedSources:reply.matches.map(x=>x.sourceId),
      inboxStatus:inbox.candidates.map(x=>x.approvalStatus),
      testReadingAllowed:reviewed.data.canUseForTestReading,
      medicalKnowledgeApproved:reviewed.data.canUseAsMedicalKnowledge,
      knowledgeVersionUpgraded:reviewed.data.canUpdateKnowledgeVersion},
    audit:{unreviewedProposalRejected:true,productionMedicalApprovalRejected:true,malformedSearchRejected:true},
    limitations:['本地回环 HTTP；没有部署公开服务','使用测试审查员，不是真人或正式医学审核',
      '模块2离线计算的候选输入是经结构化的虚构数据，非真实模型输出',
      '模块3使用真实代码中的历史示例，非网络实时查询','模块1新准备单是测试采纳，未改变正式线上预测策略']};
  mkdirSync(ex,{recursive:true});writeFileSync(join(ex,'three-module-runtime-http-results.json'),JSON.stringify(result,null,2));
  console.log(JSON.stringify({mode:result.kind,old:result.module1.originalSelected,new:result.module1.newSelected,
    candidateCount:result.module3.matchedSources.length,verified:result.audit},null,2));
})().catch(err=>{console.error(String(err));process.exitCode=1;});
