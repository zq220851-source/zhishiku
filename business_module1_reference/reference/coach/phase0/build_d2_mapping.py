def classify(text):
    """返回 (rule_id, 匹配到的关键词) 或 (None, None)"""
    for rule, pats in RULE_PATTERNS:
        for p in pats:
            m = re.search(p, text)
            if m:
                return rule, m.group(0)
    return None, None

