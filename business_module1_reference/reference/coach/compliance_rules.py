# ---------- 否定词表（共享）----------
# ★ 这份表原来在 compliance_rules 与 verify_at05 各写一份，
#   导致「不属于」在一处生效、另一处漏掉 → 正确表述被误判。
#   现在只定义一次。
NEGATION_WORDS = (
    r"(不是|并非|绝非|绝不|不可|不能|不等于|不等同|不属于|不作为|"
    r"未获批|非获批|仅为教学|仅属于教学|仅是教学|不宜|不会|不适合|"
    r"难以|不得|禁(止)?|"
    # ↓ 实测中漏掉的表达变体（正确表述被误判成宣称获批）
    r"不代表|并不|不意味|非指|不可认为|不能说|不意味着|不成立|"
    r"不宜表述|不能表述|不可表述|未获准|没(有)?获批)"
)

# 否定语境前瞻：命中点之前不得出现否定词
NEG_LOOKAHEAD = r"(?![^。；]{0,20}?" + NEGATION_WORDS + r")"

# 教学关联 → 获批适应症（专用于 LLM 输出，因为它常犯这个错）
# ★ 否定语境判断不能用正则前瞻（方向相反且窗口不可控），
#   改为匹配后检查「命中片段 + 其后 20 字」——因为否定词通常紧跟在
#   「教学关联」之后：「教学主题关联**，不代表已获批该适应症」。
TEACH_AS_INDICATION = re.compile(
    r"(教学(主题)?(关联|探讨|链接))[^。；]{0,14}(适用于|可(以)?用于|获批|适应症)|"
    r"(适用于|可(以)?用于)[^。；]{0,10}教学(主题)?(关联|探讨)")


def teaching_as_indication_hit(text):
    """
    命中「把教学关联说成适应症」则返回 match，否则 None。

    否定语境排除：检查命中片段**及其后** 20 字里有没有否定词。
    （否定词通常紧跟在「教学关联」之后，不在它之前。）
    """
    m = TEACH_AS_INDICATION.search(text or "")
    if not m:
        return None
    seg = (text or "")[m.start(): m.end() + 20]
    if re.search(NEGATION_WORDS, seg):
        return None
    return m

