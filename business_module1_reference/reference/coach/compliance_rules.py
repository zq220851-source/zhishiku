# 编译
COMPILED_RULES = [(rid, gate, desc, re.compile(pat))
                  for rid, gate, desc, pat in GATE_RULES]

RULE_BY_ID = {rid: (gate, desc) for rid, gate, desc, _p in GATE_RULES}


def has_negation_context(text, pos, window=20):
    """
    命中位置**之前**的窗口里是否有否定词。

    ★ 为什么不能用正则负向前瞻：
      负向前瞻是从匹配点**向后**看，而否定词在匹配点**之前**（方向反了）；
      Python 又不支持变长 lookbehind。
      所以只能匹配后手工回看窗口。
    """
    pre = (text or "")[max(0, pos - window):pos]
    return bool(re.search(NEGATION_WORDS, pre))


def match_rules(text, exclude_ids=(), negation_aware=True):
    """
    返回命中的规则列表 [(规则ID, 闸门, 描述, 命中文本)]

    negation_aware=True 时：命中位置前若有否定词则跳过该次命中。
    「并非该药已获批的适应症」不该被判成宣称获批。
    """
    hits = []
    for rid, gate, desc, pat in COMPILED_RULES:
        if rid in exclude_ids:
            continue
        m = pat.search(text or "")
        if m:
            if negation_aware and has_negation_context(text, m.start()):
                continue
            hits.append((rid, gate, desc, m.group(0)))
    return hits


